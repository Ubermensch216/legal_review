/**
 * 질의어 및 문서 컨텍스트에서 법률 키워드 및 동의어 다중 분기 확장
 * @param {string} query 
 * @returns {{ expandedTerms: string[], suggestedLaws: Array<{name: string, mainArticles: string[], ministry?: string}>, matchedKeywords: string[] }}
 */
export function expandQueryKeywords(query) {
  if (!query) return { expandedTerms: [], suggestedLaws: [], matchedKeywords: [] };
  
  const expandedTerms = new Set();
  const matchedLaws = new Map();
  const matchedKeywords = [];

  const normalizedQuery = query.toLowerCase();

  // 1. 일상어 ↔ 전문용어 사전 매핑
  for (const [term, lawTerms] of Object.entries(LAW_TERM_KB.synonyms)) {
    if (normalizedQuery.includes(term.toLowerCase())) {
      matchedKeywords.push(term);
      expandedTerms.add(term);
      lawTerms.forEach(lt => expandedTerms.add(lt));
    }
  }

  // 2. 도메인별 법령 매핑
  if (/개인정보|정보보호|cctv|영상정보|동의|유출|생체|안면인식|비식별|주민등록/i.test(normalizedQuery)) {
    LAW_TERM_KB.domainLaws.privacy.forEach(l => matchedLaws.set(l.name, l));
  }
  if (/근로|퇴직|휴일|임금|해고|근무|야근|연차|포괄임금|취업규칙|괴롭힘|노동/i.test(normalizedQuery)) {
    LAW_TERM_KB.domainLaws.labor.forEach(l => matchedLaws.set(l.name, l));
  }
  if (/계약|해제|해지|위약|손해배상|약관|채무|독소|하도급|수의계약|하자|면책/i.test(normalizedQuery)) {
    LAW_TERM_KB.domainLaws.contract.forEach(l => matchedLaws.set(l.name, l));
  }
  if (/처분|취소|행정|인허가|조례|과태료|영업정지|보조금|견인|법률유보|위임/i.test(normalizedQuery)) {
    LAW_TERM_KB.domainLaws.admin.forEach(l => matchedLaws.set(l.name, l));
  }
  if (/공유재산|국유재산|행정재산|일반재산|사용허가|사용료|대부료|관리위탁|감정평가|공시지가|시가표준액|전용면적|공용면적|평정가격/i.test(normalizedQuery)) {
    LAW_TERM_KB.domainLaws.publicProperty.forEach(l => matchedLaws.set(l.name, l));
  }

  return {
    expandedTerms: Array.from(expandedTerms),
    suggestedLaws: Array.from(matchedLaws.values()),
    matchedKeywords
  };
}

export default {
  LAW_TERM_KB,
  expandQueryKeywords
};
