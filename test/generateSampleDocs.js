async function generateSampleFiles() {
  console.log('[SampleGen] 테스트용 복합 검토 문서 생성 중...');

  // 1. HWPX 파일 생성
  const hwpxBuffer = await generateHwpx({
    title: '스마트시티 AI 안면인식 영상관제 운영지침(안)',
    contentMarkdown: cctvGuidelineMarkdown
  });
  const hwpxPath = path.join(targetDir, 'test_cctv_guideline.hwpx');
  fs.writeFileSync(hwpxPath, hwpxBuffer);
  console.log(`[SampleGen] HWPX 파일 생성 완료: ${hwpxPath} (${(hwpxBuffer.length / 1024).toFixed(1)} KB)`);

  // 2. PDF 파일 생성
  const pdfBuffer = await generatePdf({
    title: 'OO시 개인형 이동장치 규제 조례안 검토요청서',
    contentMarkdown: mobilityOrdinanceMarkdown
  });
  const pdfPath = path.join(targetDir, 'test_mobility_ordinance.pdf');
  fs.writeFileSync(pdfPath, pdfBuffer);
  console.log(`[SampleGen] PDF 파일 생성 완료: ${pdfPath} (${(pdfBuffer.length / 1024).toFixed(1)} KB)`);

  console.log('\n[SampleGen] 모든 테스트 문서 생성이 완료되었습니다.');
}

generateSampleFiles().catch(err => {
  console.error('[SampleGen Error]', err);
  process.exit(1);
});
